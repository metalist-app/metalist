"""Generate the character data tags and searches share between the server and the browser
(docs/ui/tag-bar.md, Whitespace + Tokens).

Run with the newest supported Python, whose Unicode version is the newest:
    python3.14 scripts/generate_tag_characters.py

It writes:
- app/static/config/tag-characters.json: the invisible characters a tag never keeps, and the
  characters whose case folding (str.casefold) differs from their lowercase, the server's
  source (app/services/tag_characters.py);
- app/static/js/modules/tag-characters-data.js: the same data for the browser, which folds a
  tag's case with it exactly as the server does;
- tests/unit/fixtures/unicode-lowercase.json: every character's lowercase, so a test checks
  that the browser lowercases each one as Python does.

tests/unit/test_tag_characters.py fails when a committed file no longer matches what this
script writes from the JSON, or when the data disagrees with the Python running the tests.
"""

from __future__ import annotations

import json
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA_PATH = ROOT / "app" / "static" / "config" / "tag-characters.json"
BROWSER_MODULE_PATH = ROOT / "app" / "static" / "js" / "modules" / "tag-characters-data.js"
LOWERCASE_FIXTURE_PATH = ROOT / "tests" / "unit" / "fixtures" / "unicode-lowercase.json"

# Spaces per level in the JSON files, so a diff of them reads line by line.
JSON_INDENT = 2
UNASSIGNED_CATEGORY = "Cn"
# Surrogates are halves of characters, not characters on their own.
SURROGATE_CATEGORY = "Cs"
# Invisible characters that would make two tags look the same while differing: the soft
# hyphen, zero-width space, direction marks and embeddings, the word joiner and invisible
# operators, direction isolates, and the byte order mark. The zero-width joiner and
# non-joiner stay: emoji sequences and scripts such as Persian need them.
INVISIBLE_CHARACTERS = (
    "\u00ad\u180e\u200b\u200e\u200f"
    "\u202a\u202b\u202c\u202d\u202e"
    "\u2060\u2061\u2062\u2063\u2064"
    "\u2066\u2067\u2068\u2069\ufeff"
)


def code_point_key(code_point: int) -> str:
    """A code point as the data files write it: four or more hexadecimal digits."""
    return f"{code_point:04X}"


def assigned_characters() -> list[str]:
    return [
        chr(code_point) for code_point in range(sys.maxunicode + 1)
        if unicodedata.category(chr(code_point)) not in (UNASSIGNED_CATEGORY, SURROGATE_CATEGORY)
    ]


def tag_character_data() -> dict[str, object]:
    casefold_exceptions = {
        code_point_key(ord(character)): character.casefold()
        for character in assigned_characters() if character.casefold() != character.lower()
    }
    return {
        "unicodeVersion": unicodedata.unidata_version,
        "invisible": [code_point_key(ord(character)) for character in INVISIBLE_CHARACTERS],
        "casefoldExceptions": casefold_exceptions,
    }


def lowercase_fixture() -> dict[str, object]:
    return {
        "unicodeVersion": unicodedata.unidata_version,
        "lowercase": {
            code_point_key(ord(character)): character.lower()
            for character in assigned_characters() if character.lower() != character
        },
    }


def json_text(value: dict[str, object]) -> str:
    return json.dumps(value, ensure_ascii=True, indent=JSON_INDENT, sort_keys=True) + "\n"


def browser_module_text(data: dict[str, object]) -> str:
    """The browser's copy of the JSON data (tag-characters.js reads it)."""
    return (
        "// Generated by scripts/generate_tag_characters.py from app/static/config/tag-characters.json.\n"
        "// Do not edit: run the script. tests/unit/test_tag_characters.py checks it matches.\n"
        f"export const TAG_CHARACTER_DATA = Object.freeze({json.dumps(data, ensure_ascii=True, sort_keys=True)});\n"
    )


def main() -> None:
    data = tag_character_data()
    DATA_PATH.write_text(json_text(data), encoding="utf-8", newline="\n")
    BROWSER_MODULE_PATH.write_text(browser_module_text(data), encoding="utf-8", newline="\n")
    LOWERCASE_FIXTURE_PATH.parent.mkdir(parents=True, exist_ok=True)
    LOWERCASE_FIXTURE_PATH.write_text(json_text(lowercase_fixture()), encoding="utf-8", newline="\n")
    sys.stdout.write(f"Unicode {unicodedata.unidata_version}: wrote {DATA_PATH.name}, "
                     f"{BROWSER_MODULE_PATH.name} and {LOWERCASE_FIXTURE_PATH.name}\n")


if __name__ == "__main__":
    main()
